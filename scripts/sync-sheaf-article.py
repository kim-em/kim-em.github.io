#!/usr/bin/env python3
"""Copy the reviewed Verso article from a clean sheaf-of-rings checkout."""
import json
from pathlib import Path
import re
import subprocess
import sys

source = Path(sys.argv[1]).resolve()
root = Path(__file__).resolve().parent.parent
revision = subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
if subprocess.check_output(['git', '-C', str(source), 'status', '--porcelain', '--', 'article/verso', 'counterexample'], text=True):
    sys.exit('Commit article and theorem changes before syncing.')
for name in ['Article', 'Note', 'Render']:
    text = (source / f'article/verso/{name}.lean').read_text()
    text = text.replace('import Article\n', 'import Site.SheafArticle.Article\n')
    (root / f'Site/SheafArticle/{name}.lean').write_text(text)
links = []
for path in sorted((source / 'counterexample').glob('*.thy')):
    for number, line in enumerate(path.read_text().splitlines(), 1):
        match = re.match(r'(?:theorem|corollary|lemma) (\w+)', line)
        if match:
            links.append((match[1], f'https://github.com/kim-em/sheaf-of-rings/blob/{revision}/counterexample/{path.name}#L{number}'))
needed = set(re.findall(r'(?:theorem|isabelle) "([^"]+)"', (source / 'article/verso/Note.lean').read_text()))
links = [(name, url) for name, url in links if name in needed]
assert {name for name, _ in links} == needed
text = f'-- Generated by scripts/sync-sheaf-article.py from kim-em/sheaf-of-rings@{revision}.\n'
text += 'import Site.SheafArticle.Render\n\nnamespace SheafArticle\n\ndef sourceLinks : Std.HashMap String String :=\n  .ofList [\n'
text += ',\n'.join(f'    ({json.dumps(name)}, {json.dumps(url)})' for name, url in links)
text += '\n  ]\n\nend SheafArticle\n'
(root / 'Site/SheafArticle/SourceLinks.lean').write_text(text)
